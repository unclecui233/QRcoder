def size_for_version(version: int) -> int:
    """Module count (width == height) of *version*."""
    return 17 + 4 * version


def version_for_size(size: int) -> int:
    """Version whose module count is *size*; 0 when the size is not a valid QR size."""
    if size < 21 or size > 177 or (size - 17) % 4:
        return 0
    return (size - 17) // 4


