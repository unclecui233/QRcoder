def data_codeword_count(version: int, level: str) -> int:
    return sum(g[0] * g[2] for g in ECC_BLOCKS[version][level])


def total_codeword_count(version: int, level: str) -> int:
    return sum(g[0] * g[1] for g in ECC_BLOCKS[version][level])


def codeword_capacity_bits(version: int) -> int:
    """Number of modules available for codewords plus remainder bits."""
    return TOTAL_CODEWORDS[version] * 8 + REMAINDER_BITS[version]


def alignment_centres(version: int) -> List[Tuple[int, int]]:
    """All alignment-pattern centre coordinates, excluding the three finder corners."""
    pos = ALIGNMENT_POSITIONS.get(version, ())
    out: List[Tuple[int, int]] = []
    for r in pos:
        for col in pos:
            if (r == 6 and col == 6) or (r == 6 and col == pos[-1]) or (r == pos[-1] and col == 6):
                continue
            out.append((r, col))
    return out
